from tests.utils.testing_utils.setup_test import setup_test
from tests.utils.testing_utils.run_test import run_test
from tests.utils.testing_utils.test_results import (
    assert_test_results,
    get_testcase_property,
)
from attribute_plugin import add_test_properties

# Starting and stopping all stress processes can take long on a loaded machine.
RUN_TIMEOUT_S = 200


@add_test_properties(
    fully_verifies=[],
    partially_verifies=[
        "feat_req__lifecycle__launch_support",
        "comp_req__launch_man__launch_parallel",
    ],
    test_type="interface-test",
    derivation_technique="explorative-testing",
)
def test_stress_launch(
    target,
    setup_test,
    assert_test_results,
    remote_test_dir,
    test_output_dir,
    record_property,
):
    """
    Objective: Verifies that the launch manager can start and stop a large number of processes.

    The configuration is generated by generate_config.py. The Run Target Stress has 1024 processes,
    the control client test driver and 1023 stress processes, half of them reporting and half of them
    native processes, which all run the same counting_process binary. The control client test driver
    activates this Run Target, checks that every stress process was started, and stops them again by
    activating the Startup Run Target.
    Expected Behaviour: Both Run Target transitions succeed and every stress process was started once.
    The duration of both transitions is recorded in the test results.
    """

    run_test(
        target=target,
        binary_path=str(remote_test_dir / "launch_manager"),
        args=["-c", str(remote_test_dir / "etc/config.bin")],
        cwd=str(remote_test_dir),
        timeout=RUN_TIMEOUT_S,
    )

    assert_test_results({"control_client_test_driver.xml"})

    driver_results = test_output_dir / "control_client_test_driver.xml"
    for name in ("activation_time_ms", "deactivation_time_ms"):
        record_property(name, get_testcase_property(driver_results, name))
